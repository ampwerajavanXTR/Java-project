    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txt_amenity_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the amenity first.");
    return;
}
int ok = JOptionPane.showConfirmDialog(this, "Delete this amenity?", "Confirm", JOptionPane.YES_NO_OPTION);
if (ok != JOptionPane.YES_OPTION) {
    return;
}
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement("DELETE FROM Amenities WHERE amenity_id = ?")) {
    ps.setString(1, txt_amenity_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No amenity with that ID." : "Amenity deleted.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

