    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txt_amenity_name.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Amenity name is required.");
    return;
}
String sql = "INSERT INTO Amenities (amenity_name, description) VALUES (?, ?)";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_amenity_name.getText());
    ps.setString(2, txt_description.getText());
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Amenity added.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String id = txt_amenity_id.getText();
        String name = txt_amenity_name.getText();
    if (id.isEmpty() && name.isEmpty()) {
      JOptionPane.showMessageDialog(this, "Type an ID or part of a name first.");
      return;
    }
    String sql;
    String value;
    
    if (!id.isEmpty()) {
       sql = "SELECT * FROM Amenities WHERE amenity_id = ?";
       value = id;
    }
    else {
    sql = "SELECT * FROM Amenities WHERE amenity_name LIKE ?";
    value = "%" + name + "%";
    }
    
    try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
     ps.setString(1, value);
    try (ResultSet rs = ps.executeQuery()) {
        if (rs.next()) {
            txt_amenity_id.setText(rs.getString("amenity_id"));
            txt_amenity_name.setText(rs.getString("amenity_name"));
            txt_description.setText(rs.getString("description"));
        } else {
            JOptionPane.showMessageDialog(this, "No matching amenity found.");
        }
    }
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txt_amenity_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the amenity first.");
    return;
}
String sql = "UPDATE Amenities SET amenity_name=?, description=? WHERE amenity_id=?";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_amenity_name.getText());
    ps.setString(2, txt_description.getText());
    ps.setString(3, txt_amenity_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No amenity with that ID." : "Amenity updated.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

