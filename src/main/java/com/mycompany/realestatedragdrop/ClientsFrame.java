    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txt_client_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the client first.");
    return;
}
String sql = "UPDATE Clients SET first_name=?, last_name=?, phone=?, email=?, client_type=? WHERE client_id=?";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_first_name.getText());
    ps.setString(2, txt_last_name.getText());
    ps.setString(3, txt_phone.getText());
    ps.setString(4, txt_email.getText());
    ps.setString(5, txt_client_type.getText());
    ps.setString(6, txt_client_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No client with that ID." : "Client updated.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txt_first_name.getText().isEmpty() || txt_last_name.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "First name and last name are required.");
    return;
}
if (txt_client_type.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Client type is required (Buyer or Tenant).");
    return;
}
String sql = "INSERT INTO Clients (first_name, last_name, phone, email, client_type) VALUES (?, ?, ?, ?, ?)";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_first_name.getText());
    ps.setString(2, txt_last_name.getText());
    ps.setString(3, txt_phone.getText());
    ps.setString(4, txt_email.getText());
    ps.setString(5, txt_client_type.getText());
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Client added.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

