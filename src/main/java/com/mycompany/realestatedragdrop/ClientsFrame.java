    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String id = txt_client_id.getText();
String first = txt_first_name.getText();
String last = txt_last_name.getText();
if (id.isEmpty() && first.isEmpty() && last.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Type an ID or part of a name first.");
    return;
}
String sql;
if (!id.isEmpty()) {
    sql = "SELECT * FROM Clients WHERE client_id = ?";
} else {
    sql = "SELECT * FROM Clients WHERE first_name LIKE ? AND last_name LIKE ?";
}
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    if (!id.isEmpty()) {
        ps.setString(1, id);
    } else {
        ps.setString(1, "%" + first + "%");
        ps.setString(2, "%" + last + "%");
    }
    try (ResultSet rs = ps.executeQuery()) {
        if (rs.next()) {
            txt_client_id.setText(rs.getString("client_id"));
            txt_first_name.setText(rs.getString("first_name"));
            txt_last_name.setText(rs.getString("last_name"));
            txt_email.setText(rs.getString("email"));
            txt_phone.setText(rs.getString("phone"));
            txt_client_type.setText(rs.getString("client_type"));
        } else {
            JOptionPane.showMessageDialog(this, "No matching client found.");
        }
    }
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txt_client_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the client first.");
    return;
}
int ok = JOptionPane.showConfirmDialog(this, "Delete this client?", "Confirm", JOptionPane.YES_NO_OPTION);
if (ok != JOptionPane.YES_OPTION) {
    return;
}
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement("DELETE FROM Clients WHERE client_id = ?")) {
    ps.setString(1, txt_client_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No client with that ID." : "Client deleted.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

