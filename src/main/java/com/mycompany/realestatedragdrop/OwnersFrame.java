    private void btnUdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUdateActionPerformed
        if (txt_owner_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please search for an owner first.");
    return;
}

String sql = "UPDATE Owners SET first_name=?, last_name=?, phone_no=?, email=?, national_id=? WHERE owner_id=?";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_first_name.getText());
    ps.setString(2, txt_last_name.getText());
    ps.setString(3, txt_phone.getText());
    ps.setString(4, txt_email.getText());
    ps.setString(5, txt_national_id.getText());
    ps.setString(6, txt_owner_id.getText());
    
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No owner found with that ID." : "Owner updated successfully.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}

    }//GEN-LAST:event_btnUdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txt_owner_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please search for an owner first.");
    return;
}

int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this owner profile?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
if (confirm != JOptionPane.YES_OPTION) {
    return;
}

try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement("DELETE FROM Owners WHERE owner_id = ?")) {
    ps.setString(1, txt_owner_id.getText());
    
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No owner found with that ID." : "Owner deleted successfully.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Cannot delete owner: This individual is still listed as the owner of an active property entry.");
}

    }//GEN-LAST:event_btnDeleteActionPerformed

