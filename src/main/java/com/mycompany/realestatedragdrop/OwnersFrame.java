    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txt_first_name.getText().isEmpty() || txt_last_name.getText().isEmpty() || txt_phone.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "First Name, Last Name, and Phone Number are required.");
    return;
}

String sql = "INSERT INTO Owners (first_name, last_name, phone_no, email, national_id) VALUES (?, ?, ?, ?, ?)";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_first_name.getText());
    ps.setString(2, txt_last_name.getText());
    ps.setString(3, txt_phone.getText());
    ps.setString(4, txt_email.getText());
    ps.setString(5, txt_national_id.getText());
    
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Owner added successfully.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}

}

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        List<String> conditions = new ArrayList<>();
List<String> values = new ArrayList<>();

if (!txt_owner_id.getText().isEmpty()) {
    conditions.add("owner_id = ?");
    values.add(txt_owner_id.getText());
}
if (!txt_first_name.getText().isEmpty()) {
    conditions.add("first_name LIKE ?");
    values.add("%" + txt_first_name.getText() + "%");
}
if (!txt_last_name.getText().isEmpty()) {
    conditions.add("last_name LIKE ?");
    values.add("%" + txt_last_name.getText() + "%");
}
if (!txt_national_id.getText().isEmpty()) {
    conditions.add("national_id = ?");
    values.add(txt_national_id.getText());
}

if (conditions.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Type an ID, Name, or National ID to search.");
    return;
}

String sql = "SELECT * FROM Owners WHERE " + String.join(" AND ", conditions) + " ORDER BY owner_id";

try (Connection c = DatabaseConnection.getConnection();

    PreparedStatement ps = c.prepareStatement(sql)) {
        for (int i = 0; i < values.size(); i++) {
        ps.setString(i + 1, values.get(i));
        }

     try (ResultSet rs = ps.executeQuery()) {
        if (rs.next()) {
            txt_owner_id.setText(rs.getString("owner_id"));
            txt_first_name.setText(rs.getString("first_name"));
            txt_last_name.setText(rs.getString("last_name"));
            txt_phone.setText(rs.getString("phone_no"));
            txt_email.setText(rs.getString("email"));
            txt_national_id.setText(rs.getString("national_id"));
        } else {
            JOptionPane.showMessageDialog(this, "No matching owner found.");
        }
        }
    } catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}

    }//GEN-LAST:event_btnSearchActionPerformed

