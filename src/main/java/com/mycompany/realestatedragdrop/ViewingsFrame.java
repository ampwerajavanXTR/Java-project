    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
                if (txt_property_id.getText().isEmpty() || txt_client_id.getText().isEmpty() 
                || txt_agent_id.getText().isEmpty() || txt_viewing_date.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Property ID, Client ID, Agent ID, and Viewing Date fields are required.");
            return;
        }

        String sql = "INSERT INTO Viewings (property_id, client_id, agent_id, viewing_date, feedback) VALUES (?, ?, ?, ?, ?)";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_property_id.getText());
            ps.setString(2, txt_client_id.getText());
            ps.setString(3, txt_agent_id.getText());
            ps.setString(4, txt_viewing_date.getText()); // Expected Format: YYYY-MM-DD
            ps.setString(5, txt_feedback.getText()); // Optional field

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Viewing appointment added successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database Error: Verify that Property ID, Client ID, and Agent ID already exist.");
        }

    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
              List<String> conditions = new ArrayList<>();
        List<String> values = new ArrayList<>();

        if (!txt_viewing_id.getText().isEmpty()) {
            conditions.add("viewing_id = ?");
            values.add(txt_viewing_id.getText());
        }
        if (!txt_property_id.getText().isEmpty()) {
            conditions.add("property_id = ?");
            values.add(txt_property_id.getText());
        }
        if (!txt_client_id.getText().isEmpty()) {
            conditions.add("client_id = ?");
            values.add(txt_client_id.getText());
        }
        if (!txt_agent_id.getText().isEmpty()) {
            conditions.add("agent_id = ?");
            values.add(txt_agent_id.getText());
        }

        if (conditions.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Type a Viewing ID, Property ID, Client ID, or Agent ID to search.");
            return;
        }

        String sql = "SELECT * FROM Viewings WHERE " + String.join(" AND ", conditions) + " ORDER BY viewing_id";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < values.size(); i++) {
                ps.setString(i + 1, values.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    txt_viewing_id.setText(rs.getString("viewing_id"));
                    txt_property_id.setText(rs.getString("property_id"));
                    txt_client_id.setText(rs.getString("client_id"));
                    txt_agent_id.setText(rs.getString("agent_id"));
                    txt_viewing_date.setText(rs.getString("viewing_date"));
                    txt_feedback.setText(rs.getString("feedback"));
                } else {
                    JOptionPane.showMessageDialog(this, "No matching viewing record found.");
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
                if (txt_viewing_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a viewing appointment first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this viewing appointment record?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement("DELETE FROM Viewings WHERE viewing_id = ?")) {
            ps.setString(1, txt_viewing_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No viewing record found with that ID." : "Viewing record deleted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
                if (txt_viewing_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a viewing appointment first.");
            return;
        }

        String sql = "UPDATE Viewings SET property_id=?, client_id=?, agent_id=?, viewing_date=?, feedback=? WHERE viewing_id=?";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_property_id.getText());
            ps.setString(2, txt_client_id.getText());
            ps.setString(3, txt_agent_id.getText());
            ps.setString(4, txt_viewing_date.getText());
            ps.setString(5, txt_feedback.getText());
            ps.setString(6, txt_viewing_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No viewing record found with that ID." : "Viewing record updated successfully.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Update Error: Verify that all relational IDs match the existing data records.");
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

