    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
                if (txt_rental_id.getText().isEmpty() || txt_amount.getText().isEmpty() || txt_payment_date.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Rental ID, Amount, and Payment Date fields are required.");
            return;
        }

        String sql = "INSERT INTO Payments (rental_id, amount, payment_date, payment_status) VALUES (?, ?, ?, ?)";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_rental_id.getText());
            ps.setString(2, txt_amount.getText());
            ps.setString(3, txt_payment_date.getText()); // Expected Format: YYYY-MM-DD
            ps.setString(4, txt_payment_status.getText());

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Payment record added successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
                if (txt_payment_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a payment record first.");
            return;
        }

        String sql = "UPDATE Payments SET rental_id=?, amount=?, payment_date=?, payment_status=? WHERE payment_id=?";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_rental_id.getText());
            ps.setString(2, txt_amount.getText());
            ps.setString(3, txt_payment_date.getText());
            ps.setString(4, txt_payment_status.getText());
            ps.setString(5, txt_payment_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No payment found with that ID." : "Payment record updated successfully.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
                if (txt_payment_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a payment record first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this payment record?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement("DELETE FROM Payments WHERE payment_id = ?")) {
            ps.setString(1, txt_payment_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No payment found with that ID." : "Payment record deleted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

