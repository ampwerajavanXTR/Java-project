    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
                List<String> conditions = new ArrayList<>();
        List<String> values = new ArrayList<>();

        if (!txt_payment_id.getText().isEmpty()) {
            conditions.add("payment_id = ?");
            values.add(txt_payment_id.getText());
        }
        if (!txt_rental_id.getText().isEmpty()) {
            conditions.add("rental_id = ?");
            values.add(txt_rental_id.getText());
        }
        if (!txt_payment_status.getText().isEmpty()) {
            conditions.add("payment_status LIKE ?");
            values.add("%" + txt_payment_status.getText() + "%");
        }

        if (conditions.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Type a Payment ID, Rental ID, or Status to search.");
            return;
        }

        String sql = "SELECT * FROM Payments WHERE " + String.join(" AND ", conditions) + " ORDER BY payment_id";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < values.size(); i++) {
                ps.setString(i + 1, values.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    txt_payment_id.setText(rs.getString("payment_id"));
                    txt_rental_id.setText(rs.getString("rental_id"));
                    txt_amount.setText(rs.getString("amount"));
                    txt_payment_date.setText(rs.getString("payment_date"));
                    txt_payment_status.setText(rs.getString("payment_status"));
                } else {
                    JOptionPane.showMessageDialog(this, "No matching payment record found.");
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnSearchActionPerformed

