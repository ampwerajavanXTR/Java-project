    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
                if (txt_contract_id.getText().isEmpty() || txt_sale_price.getText().isEmpty() 
                || txt_sale_date.getText().isEmpty() || txt_payment_method.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Contract ID, Sale Price, Sale Date, and Payment Method fields are required.");
            return;
        }

        String sql = "INSERT INTO Sales (contract_id, sale_price, sale_date, payment_method) VALUES (?, ?, ?, ?)";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_contract_id.getText());
            ps.setString(2, txt_sale_price.getText());
            ps.setString(3, txt_sale_date.getText()); // Expected Format: YYYY-MM-DD
            ps.setString(4, txt_payment_method.getText());

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Sale transaction record added successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database Error: Ensure the Contract ID exists and is valid.");
        }

    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
                List<String> conditions = new ArrayList<>();
        List<String> values = new ArrayList<>();

        if (!txt_sale_id.getText().isEmpty()) {
            conditions.add("sale_id = ?");
            values.add(txt_sale_id.getText());
        }
        if (!txt_contract_id.getText().isEmpty()) {
            conditions.add("contract_id = ?");
            values.add(txt_contract_id.getText());
        }
        if (!txt_payment_method.getText().isEmpty()) {
            conditions.add("payment_method LIKE ?");
            values.add("%" + txt_payment_method.getText() + "%");
        }

        if (conditions.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Type a Sale ID, Contract ID, or Payment Method to search.");
            return;
        }

        String sql = "SELECT * FROM Sales WHERE " + String.join(" AND ", conditions) + " ORDER BY sale_id";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < values.size(); i++) {
                ps.setString(i + 1, values.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    txt_sale_id.setText(rs.getString("sale_id"));
                    txt_contract_id.setText(rs.getString("contract_id"));
                    txt_sale_price.setText(rs.getString("sale_price"));
                    txt_sale_date.setText(rs.getString("sale_date"));
                    txt_payment_method.setText(rs.getString("payment_method"));
                } else {
                    JOptionPane.showMessageDialog(this, "No matching sale transaction found.");
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
                if (txt_sale_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a sale record first.");
            return;
        }

        String sql = "UPDATE Sales SET contract_id=?, sale_price=?, sale_date=?, payment_method=? WHERE sale_id=?";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_contract_id.getText());
            ps.setString(2, txt_sale_price.getText());
            ps.setString(3, txt_sale_date.getText());
            ps.setString(4, txt_payment_method.getText());
            ps.setString(5, txt_sale_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No sale record found with that ID." : "Sale transaction updated successfully.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
                if (txt_sale_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a sale record first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to permanently delete this sale record?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement("DELETE FROM Sales WHERE sale_id = ?")) {
            ps.setString(1, txt_sale_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No sale record found with that ID." : "Sale record deleted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

