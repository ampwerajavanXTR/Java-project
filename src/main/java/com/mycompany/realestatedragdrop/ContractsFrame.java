    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txt_property_id.getText().isEmpty() || txt_client_id.getText().isEmpty()
        //|| txt_agent_id.getText().isEmpty() || txt_contract_type.getText().isEmpty()
        || txt_start_date.getText().isEmpty() || txt_contract_status.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Fill in everything except Contract ID and End Date.");
    return;
}
String sql = "INSERT INTO Contracts (property_id, client_id, agent_id, contract_type, start_date, end_date, contract_status) "
           + "VALUES (?, ?, ?, ?, ?, ?, ?)";

try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_property_id.getText());
    ps.setString(2, txt_client_id.getText());
    //ps.setString(3, txt_agent_id.getText());
    ps.setString(4, txt_contract_type.getText());
    ps.setString(5, txt_start_date.getText());
    ps.setString(6, valueOrNull(txt_end_date));
    ps.setString(7, txt_contract_status.getText());
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Contract added.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
       List<String> conditions = new ArrayList<>();
       List<String> values = new ArrayList<>();

if (!txt_contract_id.getText().isEmpty()) {
    conditions.add("contract_id = ?");
    values.add(txt_contract_id.getText());
}
if (!txt_property_id.getText().isEmpty()) {
    conditions.add("property_id = ?");
    values.add(txt_property_id.getText());
}
if (!txt_client_id.getText().isEmpty()) {
    conditions.add("client_id = ?");
    values.add(txt_client_id.getText());
}

if (!txt_contract_type.getText().isEmpty()) {
    conditions.add("contract_type LIKE ?");
    values.add("%" + txt_contract_type.getText() + "%");
}
if (!txt_contract_status.getText().isEmpty()) {
    conditions.add("contract_status LIKE ?");
    values.add("%" + txt_contract_status.getText() + "%");
}

if (conditions.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Type an ID, type or status to search for.");
    return;
}

String sql = "SELECT * FROM Contracts WHERE " + String.join(" AND ", conditions) + " ORDER BY contract_id";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    for (int i = 0; i < values.size(); i++) {
        ps.setString(i + 1, values.get(i));
    }
    try (ResultSet rs = ps.executeQuery()) {
        if (rs.next()) {
            txt_contract_id.setText(rs.getString("contract_id"));
            txt_property_id.setText(rs.getString("property_id"));
            txt_client_id.setText(rs.getString("client_id"));
           // txt_agent_id.setText(rs.getString("agent_id"));
            txt_contract_type.setText(rs.getString("contract_type"));
            txt_start_date.setText(rs.getString("start_date"));
            txt_end_date.setText(rs.getString("end_date"));
            txt_contract_status.setText(rs.getString("contract_status"));
        } else {
            JOptionPane.showMessageDialog(this, "No matching contract found.");
        }
    }
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txt_contract_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the contract first.");
    return;
}
int ok = JOptionPane.showConfirmDialog(this, "Delete this contract?", "Confirm", JOptionPane.YES_NO_OPTION);
if (ok != JOptionPane.YES_OPTION) {
    return;
}
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement("DELETE FROM Contracts WHERE contract_id = ?")) {
    ps.setString(1, txt_contract_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No contract with that ID." : "Contract deleted.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txt_contract_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the contract first.");
    return;
}
String sql = "UPDATE Contracts SET property_id=?, client_id=?, agent_id=?, contract_type=?, "
           + "start_date=?, end_date=?, contract_status=? WHERE contract_id=?";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_property_id.getText());
    ps.setString(2, txt_client_id.getText());
    //ps.setString(3, txt_agent_id.getText());
    ps.setString(4, txt_contract_type.getText());
    ps.setString(5, txt_start_date.getText());
    ps.setString(6, valueOrNull(txt_end_date));
    ps.setString(7, txt_contract_status.getText());
    ps.setString(8, txt_contract_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No contract with that ID." : "Contract updated.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

