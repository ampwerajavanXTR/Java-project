    private void doLogin(javax.swing.JTextField user, javax.swing.JPasswordField pass) {
        if (user == null || pass == null) {
            javax.swing.JOptionPane.showMessageDialog(this,"Add txtUsername (JTextField) and txtPassword (JPasswordField) to the form.");
            return;
        }
        String username = user.getText();
        String password = new String(pass.getPassword());
        
        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Enter both username and password.",
                    "Missing details", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        String sql = "SELECT full_name, role FROM SystemUsers WHERE username = ? AND password = ? AND status = 'Active'";
        try (java.sql.Connection c = com.mycompany.realestatedragdrop.database.DatabaseConnection.getConnection();
             java.sql.PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, username);
            ps.setString(2, password);
            try (java.sql.ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    new MainDashboard(rs.getString("full_name"), rs.getString("role")).setVisible(true);
                    dispose();
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "Invalid username or password, or the account is inactive.",
                            "Login failed", javax.swing.JOptionPane.ERROR_MESSAGE);
                    pass.setText("");
                }
            }
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database error:\n" + ex.getMessage(),
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

