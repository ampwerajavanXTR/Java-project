    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txt_agency_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the agency first.");
    return;
}
String sql = "UPDATE Agencies SET agency_name=?, address=?, phone=?, email=? WHERE agency_id=?";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_agency_name.getText());
    ps.setString(2, txt_address.getText());
    ps.setString(3, txt_phone.getText());
    ps.setString(4, txt_email.getText());
    ps.setString(5, txt_agency_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No agency with that ID." : "Agency updated.");
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String id = txt_agency_id.getText();
String name = txt_agency_name.getText();
if (id.isEmpty() && name.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Type an ID or part of a name first.");
    return;
}
String sql;
String value;
if (!id.isEmpty()) {
    sql = "SELECT * FROM Agencies WHERE agency_id = ?";
    value = id;
} else {
    sql = "SELECT * FROM Agencies WHERE agency_name LIKE ?";
    value = "%" + name + "%";
}
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, value);
    try (ResultSet rs = ps.executeQuery()) {
        if (rs.next()) {
            txt_agency_id.setText(rs.getString("agency_id"));
            txt_agency_name.setText(rs.getString("agency_name"));
            txt_address.setText(rs.getString("address"));
            txt_phone.setText(rs.getString("phone"));
            txt_email.setText(rs.getString("email"));
        } else {
            JOptionPane.showMessageDialog(this, "No matching agency found.");
        }
    }
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnSearchActionPerformed

