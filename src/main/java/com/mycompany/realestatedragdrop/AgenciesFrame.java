    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {
        if (txt_agency_name.getText().isEmpty()) {
         JOptionPane.showMessageDialog(this, "Agency name is required.");
         return;
         }
    String sql = "INSERT INTO Agencies (agency_name, address, phone, email) VALUES (?, ?, ?, ?)";
    
    try (
        Connection c = DatabaseConnection.getConnection();
        PreparedStatement ps = c.prepareStatement(sql)) 
        {
        ps.setString(1, txt_agency_name.getText());
        ps.setString(2, txt_address.getText());
        ps.setString(3, txt_phone.getText());
        ps.setString(4, txt_email.getText());
        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Agency added.");
        clearFields();
       
    } 
    catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
     }
    }                                      

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {
    if (txt_agency_id.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Search for the agency first.");
    return;
    }
    int ok = JOptionPane.showConfirmDialog(this, "Delete this agency?", "Confirm", JOptionPane.YES_NO_OPTION);
    if (ok != JOptionPane.YES_OPTION) {
    return;
    }
     try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement("DELETE FROM Agencies WHERE agency_id = ?")) {
     ps.setString(1, txt_agency_id.getText());
    int n = ps.executeUpdate();
    JOptionPane.showMessageDialog(this, n == 0 ? "No agency with that ID." : "Agency deleted.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }                                         

