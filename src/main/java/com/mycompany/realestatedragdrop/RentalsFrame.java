    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
                if (txt_contract_id.getText().isEmpty() || txt_monthly_rent.getText().isEmpty() 
                || deposit_amount.getText().isEmpty() || txt_lease_start.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Contract ID, Monthly Rent, Deposit Amount, and Lease Start are required.");
            return;
        }

        String sql = "INSERT INTO Rentals (contract_id, monthly_rent, deposit_amount, lease_start, lease_end) VALUES (?, ?, ?, ?, ?)";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_contract_id.getText());
            ps.setString(2, txt_monthly_rent.getText());
            ps.setString(3, deposit_amount.getText());
            ps.setString(4, txt_lease_start.getText()); // Format: YYYY-MM-DD
            ps.setString(5, valueOrNull(txt_lease_end)); // Can be null if ongoing

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Rental agreement record added successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database Error: Ensure the Contract ID already exists in the Contracts table.");
        }

    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
                if (txt_rental_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a rental record first.");
            return;
        }

        String sql = "UPDATE Rentals SET contract_id=?, monthly_rent=?, deposit_amount=?, lease_start=?, lease_end=? WHERE rental_id=?";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_contract_id.getText());
            ps.setString(2, txt_monthly_rent.getText());
            ps.setString(3, deposit_amount.getText());
            ps.setString(4, txt_lease_start.getText());
            ps.setString(5, valueOrNull(txt_lease_end));
            ps.setString(6, txt_rental_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No rental record found with that ID." : "Rental agreement updated successfully.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
                List<String> conditions = new ArrayList<>();
        List<String> values = new ArrayList<>();

        if (!txt_rental_id.getText().isEmpty()) {
            conditions.add("rental_id = ?");
            values.add(txt_rental_id.getText());
        }
        if (!txt_contract_id.getText().isEmpty()) {
            conditions.add("contract_id = ?");
            values.add(txt_contract_id.getText());
        }

        if (conditions.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Type a Rental ID or Contract ID to search.");
            return;
        }

        String sql = "SELECT * FROM Rentals WHERE " + String.join(" AND ", conditions) + " ORDER BY rental_id";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < values.size(); i++) {
                ps.setString(i + 1, values.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    txt_rental_id.setText(rs.getString("rental_id"));
                    txt_contract_id.setText(rs.getString("contract_id"));
                    txt_monthly_rent.setText(rs.getString("monthly_rent"));
                    deposit_amount.setText(rs.getString("deposit_amount"));
                    txt_lease_start.setText(rs.getString("lease_start"));
                    txt_lease_end.setText(rs.getString("lease_end"));
                } else {
                    JOptionPane.showMessageDialog(this, "No matching rental agreement found.");
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
                if (txt_rental_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a rental record first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this rental record?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement("DELETE FROM Rentals WHERE rental_id = ?")) {
            ps.setString(1, txt_rental_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No rental record found with that ID." : "Rental record deleted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Cannot delete rental record: This record is currently linked to processed payment history logs.");
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

