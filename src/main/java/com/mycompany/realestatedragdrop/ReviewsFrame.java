    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
                if (txt_property_id.getText().isEmpty() || txt_client_id.getText().isEmpty() 
                || txt_rating.getText().isEmpty() || txt_review_date.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Property ID, Client ID, Rating, and Review Date fields are required.");
            return;
        }

        String sql = "INSERT INTO Reviews (property_id, client_id, rating, comment, review_date) VALUES (?, ?, ?, ?, ?)";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_property_id.getText());
            ps.setString(2, txt_client_id.getText());
            ps.setString(3, txt_rating.getText());
            ps.setString(4, txt_comment.getText()); // Optional comment
            ps.setString(5, txt_review_date.getText()); // Expected Format: YYYY-MM-DD

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Review posted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database Error: Ensure the Property ID and Client ID exist in the system.");
        }

    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
                List<String> conditions = new ArrayList<>();
        List<String> values = new ArrayList<>();

        if (!txt_review_id.getText().isEmpty()) {
            conditions.add("review_id = ?");
            values.add(txt_review_id.getText());
        }
        if (!txt_property_id.getText().isEmpty()) {
            conditions.add("property_id = ?");
            values.add(txt_property_id.getText());
        }
        if (!txt_client_id.getText().isEmpty()) {
            conditions.add("client_id = ?");
            values.add(txt_client_id.getText());
        }

        if (conditions.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Type a Review ID, Property ID, or Client ID to search.");
            return;
        }

        String sql = "SELECT * FROM Reviews WHERE " + String.join(" AND ", conditions) + " ORDER BY review_id";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < values.size(); i++) {
                ps.setString(i + 1, values.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    txt_review_id.setText(rs.getString("review_id"));
                    txt_property_id.setText(rs.getString("property_id"));
                    txt_client_id.setText(rs.getString("client_id"));
                    txt_rating.setText(rs.getString("rating"));
                    txt_comment.setText(rs.getString("comment"));
                    txt_review_date.setText(rs.getString("review_date"));
                } else {
                    JOptionPane.showMessageDialog(this, "No matching review found.");
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
                if (txt_review_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a review record first.");
            return;
        }

        String sql = "UPDATE Reviews SET property_id=?, client_id=?, rating=?, comment=?, review_date=? WHERE review_id=?";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_property_id.getText());
            ps.setString(2, txt_client_id.getText());
            ps.setString(3, txt_rating.getText());
            ps.setString(4, txt_comment.getText());
            ps.setString(5, txt_review_date.getText());
            ps.setString(6, txt_review_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No review found with that ID." : "Review record updated successfully.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
               if (txt_review_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a review record first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to permanently delete this review?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement("DELETE FROM Reviews WHERE review_id = ?")) {
            ps.setString(1, txt_review_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No review found with that ID." : "Review deleted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

