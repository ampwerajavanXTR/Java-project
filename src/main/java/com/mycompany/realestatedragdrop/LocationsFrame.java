    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (txt_location_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a location first.");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this location?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }
        
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement("DELETE FROM Locations WHERE location_id = ?")) {
            ps.setString(1, txt_location_id.getText());
            
            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No location found with that ID." : "Location deleted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Cannot delete location: It is currently linked to an active property database record.");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

