    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (txt_district.getText().isEmpty() || txt_city.getText().isEmpty() || txt_address.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "District, City, and Address fields are required.");
            return;
        }
        
        String sql = "INSERT INTO Locations (district, city, address, landmark) VALUES (?, ?, ?, ?)";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_district.getText());
            ps.setString(2, txt_city.getText());
            ps.setString(3, txt_address.getText());
            ps.setString(4, txt_landmark.getText());
            
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Location added successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (txt_location_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a location first.");
            return;
        }
        
        String sql = "UPDATE Locations SET district=?, city=?, address=?, landmark=? WHERE location_id=?";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_district.getText());
            ps.setString(2, txt_city.getText());
            ps.setString(3, txt_address.getText());
            ps.setString(4, txt_landmark.getText());
            ps.setString(5, txt_location_id.getText());
            
            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No location found with that ID." : "Location updated successfully.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        List<String> conditions = new ArrayList<>();
        List<String> values = new ArrayList<>();

        if (!txt_location_id.getText().isEmpty()) {
            conditions.add("location_id = ?");
            values.add(txt_location_id.getText());
        }
        if (!txt_district.getText().isEmpty()) {
            conditions.add("district LIKE ?");
            values.add("%" + txt_district.getText() + "%");
        }
        if (!txt_city.getText().isEmpty()) {
            conditions.add("city LIKE ?");
            values.add("%" + txt_city.getText() + "%");
        }

        if (conditions.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Type a Location ID, District, or City to search.");
            return;
        }

        String sql = "SELECT * FROM Locations WHERE " + String.join(" AND ", conditions) + " ORDER BY location_id";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            for (int i = 0; i < values.size(); i++) {
                ps.setString(i + 1, values.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    txt_location_id.setText(rs.getString("location_id"));
                    txt_district.setText(rs.getString("district"));
                    txt_city.setText(rs.getString("city"));
                    txt_address.setText(rs.getString("address"));
                    txt_landmark.setText(rs.getString("landmark"));
                } else {
                    JOptionPane.showMessageDialog(this, "No matching location found.");
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

