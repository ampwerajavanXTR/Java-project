    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
                if (txt_type_id.getText().isEmpty() || txt_location_id.getText().isEmpty() 
                || txt_owner_id.getText().isEmpty() || txt_agent_id.getText().isEmpty() 
                || txt_title.getText().isEmpty() || txt_price.getText().isEmpty() 
                || txt_date_listed.getText().isEmpty() || txt_status.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields except Property ID and Description are required.");
            return;
        }

        String sql = "INSERT INTO Properties (type_id, location_id, owner_id, agent_id, title, description, price, date_listed, status) "
                   + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";
        try (Connection c = DatabaseConnection.getConnection();
            PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_type_id.getText());
            ps.setString(2, txt_location_id.getText());
            ps.setString(3, txt_owner_id.getText());
            ps.setString(4, txt_agent_id.getText());
            ps.setString(5, txt_title.getText());
            ps.setString(6, txt_description.getText());
            ps.setString(7, txt_price.getText());
            ps.setString(8, txt_date_listed.getText()); // Expected Format: YYYY-MM-DD
            ps.setString(9, txt_status.getText());

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Property listing added successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database Error: Ensure Type ID, Location ID, Owner ID, and Agent ID already exist.");
        }

    }//GEN-LAST:event_btnAddActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
         List<String> conditions = new ArrayList<>();
        List<String> values = new ArrayList<>();

        // Checks input fields and builds dynamic conditions safely
        if (!xt_property_id.getText().isEmpty()) {
            conditions.add("property_id = ?");
            values.add(xt_property_id.getText());
        }
        if (!txt_type_id.getText().isEmpty()) {
            conditions.add("type_id = ?");
            values.add(txt_type_id.getText());
        }
        if (!txt_location_id.getText().isEmpty()) {
            conditions.add("location_id = ?");
            values.add(txt_location_id.getText());
        }
        if (!txt_title.getText().isEmpty()) {
            conditions.add("title LIKE ?");
            values.add("%" + txt_title.getText() + "%");
        }
        if (!txt_status.getText().isEmpty()) {
            conditions.add("status LIKE ?");
            values.add("%" + txt_status.getText() + "%");
        }

        if (conditions.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Type a Property ID, Type, Location, Title, or Status to search.");
            return;
        }

        String sql = "SELECT * FROM Properties WHERE " + String.join(" AND ", conditions) + " ORDER BY property_id";
        
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            
            for (int i = 0; i < values.size(); i++) {
                ps.setString(i + 1, values.get(i));
            }
            
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    // Populate every text field on your interface form
                    xt_property_id.setText(rs.getString("property_id"));
                    txt_title.setText(rs.getString("title"));
                    txt_description.setText(rs.getString("description"));
                    txt_price.setText(rs.getString("price"));
                    txt_status.setText(rs.getString("status"));
                    txt_type_id.setText(rs.getString("type_id"));
                    txt_location_id.setText(rs.getString("location_id"));
                    txt_owner_id.setText(rs.getString("owner_id"));
                    txt_agent_id.setText(rs.getString("agent_id"));
                    txt_date_listed.setText(rs.getString("date_listed"));
                } else {
                    JOptionPane.showMessageDialog(this, "No matching property found.");
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error during search: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
                if (xt_property_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a property listing first.");
            return;
        }

        String sql = "UPDATE Properties SET type_id=?, location_id=?, owner_id=?, agent_id=?, title=?, description=?, price=?, date_listed=?, status=? WHERE property_id=?";
        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, txt_type_id.getText());
            ps.setString(2, txt_location_id.getText());
            ps.setString(3, txt_owner_id.getText());
            ps.setString(4, txt_agent_id.getText());
            ps.setString(5, txt_title.getText());
            ps.setString(6, txt_description.getText());
            ps.setString(7, txt_price.getText());
            ps.setString(8, txt_date_listed.getText());
            ps.setString(9, txt_status.getText());
            ps.setString(10, xt_property_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No property found with that ID." : "Property listing updated successfully.");
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Update Error: Verify all relational Foreign Key IDs are valid.");
        }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
                if (xt_property_id.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please search for a property listing first.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this property record?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try (Connection c = DatabaseConnection.getConnection();
             PreparedStatement ps = c.prepareStatement("DELETE FROM Properties WHERE property_id = ?")) {
            ps.setString(1, xt_property_id.getText());

            int n = ps.executeUpdate();
            JOptionPane.showMessageDialog(this, n == 0 ? "No property found with that ID." : "Property record deleted successfully.");
            clearFields();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Cannot delete property: This property record is currently linked to active lease agreements or transaction history.");
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

