    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//btnAddActionPerformed
        if (txt_first_name.getText().isEmpty() || txt_last_name.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "First name and last name are required.");
    return;
}
String agencyId = txt_agency_id.getText();
String sql = "INSERT INTO Agents (first_name, last_name, phone, email, agency_id) VALUES (?, ?, ?, ?, ?)";
try (Connection c = DatabaseConnection.getConnection();
     PreparedStatement ps = c.prepareStatement(sql)) {
    ps.setString(1, txt_first_name.getText());
    ps.setString(2, txt_last_name.getText());
    ps.setString(3, txt_phone.getText());
    ps.setString(4, txt_email.getText());
    ps.setString(5, agencyId.isEmpty() ? null : agencyId);
    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Agent added.");
    clearFields();
} catch (SQLException ex) {
    JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
}
    }//GEN-LAST:event_btnAddActionPerformed

